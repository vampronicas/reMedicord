package com.remedicord.domain.policy

import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.time.Duration
import java.time.Instant
import kotlin.math.abs
import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class PostponePolicyTest {
    private val now = Instant.parse("2026-11-09T22:00:00Z")
    private fun at(h: Long, m: Long = 0) = Instant.parse("2026-11-10T00:00:00Z").plus(Duration.ofHours(h)).plus(Duration.ofMinutes(m))
    private fun dose(id: Long, med: Long, due: Instant) = PostponePolicy.Dose(id, med, due, due)

    // Tomorrow: 06:00 (meds 1+2 together), 12:00 (med 1), 18:00 (med 2), 22:00 (med 1)
    private val upcoming = listOf(dose(1, 1, at(6)), dose(2, 2, at(6)), dose(3, 1, at(12)), dose(4, 2, at(18)), dose(5, 1, at(22)))

    @Test fun movesTheNextNReminderTimesForAllMedicines() {
        val moves = PostponePolicy.plan(upcoming, count = 1, hours = 2, now = now)
        assertEquals(setOf(1L, 2L), moves.map { it.id }.toSet()) // both 06:00 doses ring together
        assertTrue(moves.all { it.to == at(8) })
        assertEquals(setOf(1L, 2L, 3L), PostponePolicy.plan(upcoming, 2, 1, now).map { it.id }.toSet())
    }

    @Test fun neverPushedPastTheMedicinesNextDose() {
        // Med 1: 06:00 + 8 h would be 14:00, but its next dose is 12:00 → stops at 11:59.
        val m = PostponePolicy.plan(upcoming, 1, 8, now).first { it.id == 1L }
        assertEquals(at(11, 59), m.to)
        // Med 2: next dose 18:00, so 06:00 + 8 h = 14:00 is fine.
        assertEquals(at(14), PostponePolicy.plan(upcoming, 1, 8, now).first { it.id == 2L }.to)
    }

    @Test fun pastRemindersAreIgnoredAndLimitsEnforced() {
        val withPast = upcoming + dose(9, 3, now.minus(Duration.ofHours(1)))
        assertTrue(PostponePolicy.plan(withPast, 1, 2, now).none { it.id == 9L })
        assertThrows(IllegalArgumentException::class.java) { PostponePolicy.plan(upcoming, 4, 2, now) }
        assertThrows(IllegalArgumentException::class.java) { PostponePolicy.plan(upcoming, 0, 2, now) }
        assertThrows(IllegalArgumentException::class.java) { PostponePolicy.plan(upcoming, 1, 13, now) }
        assertTrue(PostponePolicy.plan(emptyList(), 3, 2, now).isEmpty())
    }
}

/** v1.3: the bundled tones must be valid, short and gentle (generated by tools/generate_tones.ps1). */
class ToneFilesTest {
    private val names = listOf("tone_chime.wav", "tone_beep.wav", "tone_bell.wav")

    @Test fun tonesAreShortQuietPcmWavFiles() {
        names.forEach { name ->
            val bytes = File("src/main/res/raw/$name").readBytes()
            val b = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN)
            assertEquals("RIFF", String(bytes, 0, 4)); assertEquals("WAVE", String(bytes, 8, 4))
            assertEquals(1, b.getShort(20).toInt())      // PCM
            assertEquals(1, b.getShort(22).toInt())      // mono
            val rate = b.getInt(24)
            assertEquals(16, b.getShort(34).toInt())     // 16-bit
            val dataLen = b.getInt(40)
            val seconds = dataLen / 2.0 / rate
            assertTrue("$name is $seconds s", seconds in 0.3..3.0)
            var peak = 0
            for (i in 0 until dataLen / 2) peak = maxOf(peak, abs(b.getShort(44 + i * 2).toInt()))
            assertTrue("$name peak $peak is too loud", peak <= (32767 * 0.35).toInt())
            assertTrue("$name is silent", peak > 1000)
            val last = abs(b.getShort(44 + dataLen - 2).toInt())
            assertTrue("$name should end quietly (no click)", last < 200)
        }
    }
}
