package com.remedicord.reminders

import android.Manifest
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import android.os.Build
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat
import androidx.core.content.ContextCompat
import androidx.core.net.toUri
import com.remedicord.MainActivity
import com.remedicord.R
import com.remedicord.domain.schedule.ReminderText

/** Notification channels and builders (PLAN.md §3 privacy, §4.6 actions). */
object Notifications {
    const val CH_GENERAL = "general"
    private const val REMINDER_PREFIX = "reminders_"
    private const val LEGACY_REMINDERS = "reminders"

    /**
     * v1.3 reminder sounds: three gentle tones made for reMedicord (res/raw, generated by tools/generate_tones.ps1),
     * the phone's default notification sound, or silent.
     */
    enum class ReminderSound(val label: String, val rawRes: Int?) {
        CHIME("Gentle chime", R.raw.tone_chime),
        BEEP("Soft beep", R.raw.tone_beep),
        BELL("Calm bell", R.raw.tone_bell),
        DEFAULT("Phone default", null),
        SILENT("Silent (vibrate only)", null),
    }

    /**
     * Android fixes a channel's sound when it is created, and restores old settings if a deleted id is reused.
     * So each sound choice gets a fresh id: "reminders_<SOUND>_<timestamp>". The current choice is read from the id.
     */
    fun reminderChannelId(context: Context): String {
        val nm = context.getSystemService(NotificationManager::class.java)
        return nm.notificationChannels.map { it.id }.filter { it.startsWith(REMINDER_PREFIX) }.maxOrNull()
            ?: setReminderSound(context, ReminderSound.CHIME)
    }

    fun currentSound(context: Context): ReminderSound =
        reminderChannelId(context).removePrefix(REMINDER_PREFIX).substringBefore('_').let { key ->
            ReminderSound.entries.firstOrNull { it.name == key } ?: ReminderSound.CHIME
        }

    /** Replaces the reminder channel with one that uses [sound]. Returns the new channel id. */
    fun setReminderSound(context: Context, sound: ReminderSound): String {
        val nm = context.getSystemService(NotificationManager::class.java)
        val id = "$REMINDER_PREFIX${sound.name}_${System.currentTimeMillis()}"
        nm.createNotificationChannel(
            NotificationChannel(id, "Medication reminders", NotificationManager.IMPORTANCE_HIGH).apply {
                description = "Reminders to take, apply or change your medicines (sound: ${sound.label})"
                lockscreenVisibility = android.app.Notification.VISIBILITY_PRIVATE
                enableVibration(true)
                val attrs = android.media.AudioAttributes.Builder()
                    .setUsage(android.media.AudioAttributes.USAGE_NOTIFICATION_EVENT)
                    .setContentType(android.media.AudioAttributes.CONTENT_TYPE_SONIFICATION).build()
                when (sound) {
                    ReminderSound.SILENT -> setSound(null, null)
                    ReminderSound.DEFAULT -> setSound(android.provider.Settings.System.DEFAULT_NOTIFICATION_URI, attrs)
                    else -> setSound(soundUri(context, sound), attrs)
                }
            },
        )
        nm.notificationChannels.map { it.id }.filter { (it.startsWith(REMINDER_PREFIX) || it == LEGACY_REMINDERS) && it != id }
            .forEach { nm.deleteNotificationChannel(it) }
        return id
    }

    fun soundUri(context: Context, sound: ReminderSound): android.net.Uri? =
        sound.rawRes?.let { "android.resource://${context.packageName}/$it".toUri() }

    fun createChannels(context: Context) {
        val nm = context.getSystemService(NotificationManager::class.java)
        // First run, or upgrade from v1.2 (legacy "reminders" channel without a custom sound) → gentle chime.
        if (nm.notificationChannels.none { it.id.startsWith(REMINDER_PREFIX) }) setReminderSound(context, ReminderSound.CHIME)
        nm.createNotificationChannel(
            NotificationChannel(CH_GENERAL, "General", NotificationManager.IMPORTANCE_DEFAULT).apply {
                description = "Backup reminders and app messages"
                lockscreenVisibility = android.app.Notification.VISIBILITY_PRIVATE
            },
        )
    }

    /** Android 13+ needs the runtime permission; Android 12 only has the per-app "notifications on" switch. */
    fun canPost(context: Context): Boolean =
        if (Build.VERSION.SDK_INT >= 33) {
            ContextCompat.checkSelfPermission(context, Manifest.permission.POST_NOTIFICATIONS) == PackageManager.PERMISSION_GRANTED
        } else {
            NotificationManagerCompat.from(context).areNotificationsEnabled()
        }

    fun canUseFullScreen(context: Context): Boolean =
        Build.VERSION.SDK_INT < 34 || context.getSystemService(NotificationManager::class.java).canUseFullScreenIntent()

    /** Generic lock-screen version: no medicine data. */
    private fun publicVersion(context: Context) = NotificationCompat.Builder(context, reminderChannelId(context))
        .setSmallIcon(R.drawable.ic_launcher_monochrome)
        .setContentTitle(ReminderText.PUBLIC_TITLE)
        .setContentText(ReminderText.PUBLIC_TEXT)
        .build()

    private fun alarmActivityIntent(context: Context, slotId: Long, requestOffset: Int, openChoices: Boolean = false) = PendingIntent.getActivity(
        context, (slotId * 4 + requestOffset).toInt(),
        Intent(context, AlarmActivity::class.java).putExtra(AlarmScheduler.EXTRA_SLOT, slotId)
            .putExtra(AlarmActivity.EXTRA_CHOICES, openChoices).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK),
        PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
    )

    private fun actionIntent(context: Context, slotId: Long, action: String, code: Int) = PendingIntent.getBroadcast(
        context, (slotId * 4 + code).toInt(),
        Intent(context, DoseActionReceiver::class.java).setAction(action).putExtra(AlarmScheduler.EXTRA_SLOT, slotId),
        PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
    )

    /**
     * One grouped notification per slot. Taken / Skip require the phone to be unlocked
     * (setAuthenticationRequired, PLAN.md A2); Snooze works while locked.
     */
    fun postSlot(context: Context, slotId: Long, lines: List<ReminderText.Line>, snoozeMinutes: Int, canSnooze: Boolean, fullScreen: Boolean) {
        if (!canPost(context) || lines.isEmpty()) return
        val style = NotificationCompat.InboxStyle().also { s -> lines.forEach { s.addLine(ReminderText.line(it)) } }
        val b = NotificationCompat.Builder(context, reminderChannelId(context))
            .setSmallIcon(R.drawable.ic_launcher_monochrome)
            .setContentTitle(ReminderText.title(lines))
            .setContentText(ReminderText.line(lines.first()))
            .setStyle(style)
            .setCategory(NotificationCompat.CATEGORY_ALARM)
            .setPriority(NotificationCompat.PRIORITY_HIGH)
            .setVisibility(NotificationCompat.VISIBILITY_PRIVATE)
            .setPublicVersion(publicVersion(context))
            .setAutoCancel(false)
            .setContentIntent(alarmActivityIntent(context, slotId, 0))
            .addAction(
                NotificationCompat.Action.Builder(0, if (lines.size == 1) "Taken" else "Taken (all)", actionIntent(context, slotId, DoseActionReceiver.ACTION_TAKEN, 1))
                    .setAuthenticationRequired(true).build(),
            )
        // "Later": stop reminding, ask on the next app open. "Skip…" opens the reminder screen with all choices
        // (skip this dose, don't remind me again today, snooze 5/10/15) — details only after unlock.
        b.addAction(NotificationCompat.Action.Builder(0, "Later", actionIntent(context, slotId, DoseActionReceiver.ACTION_LATER, 2)).build())
        b.addAction(NotificationCompat.Action.Builder(0, "Skip…", alarmActivityIntent(context, slotId, 3, openChoices = true)).build())
        if (fullScreen && canUseFullScreen(context)) b.setFullScreenIntent(alarmActivityIntent(context, slotId, 0), true)
        notifySafely(context, slotId.toInt(), b.build())
    }

    /** Before the first unlock after a restart: generic text only, opens the app (PLAN.md §5). */
    fun postLockedGeneric(context: Context, slotId: Long) {
        if (!canPost(context)) return
        val open = PendingIntent.getActivity(context, 0, Intent(context, MainActivity::class.java), PendingIntent.FLAG_IMMUTABLE)
        val n = NotificationCompat.Builder(context, reminderChannelId(context))
            .setSmallIcon(R.drawable.ic_launcher_monochrome)
            .setContentTitle(ReminderText.PUBLIC_TITLE)
            .setContentText(ReminderText.PUBLIC_TEXT)
            .setCategory(NotificationCompat.CATEGORY_ALARM)
            .setPriority(NotificationCompat.PRIORITY_HIGH)
            .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
            .setContentIntent(open)
            .build()
        notifySafely(context, slotId.toInt(), n)
    }

    fun postGeneral(context: Context, id: Int, title: String, text: String) {
        if (!canPost(context)) return
        val open = PendingIntent.getActivity(context, 0, Intent(context, MainActivity::class.java), PendingIntent.FLAG_IMMUTABLE)
        notifySafely(context, id, NotificationCompat.Builder(context, CH_GENERAL).setSmallIcon(R.drawable.ic_launcher_monochrome)
            .setContentTitle(title).setContentText(text).setContentIntent(open).setAutoCancel(true).build())
    }

    fun cancel(context: Context, id: Int) = NotificationManagerCompat.from(context).cancel(id)

    @android.annotation.SuppressLint("MissingPermission") // checked by canPost() for every API level
    private fun notifySafely(context: Context, id: Int, n: android.app.Notification) {
        if (canPost(context)) NotificationManagerCompat.from(context).notify(id, n)
    }
}
